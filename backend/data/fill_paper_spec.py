"""
Auto-fills [TO BE FILLED] placeholders in paper_spec_filled.md from
eval summary CSVs.

Usage:
    python data/fill_paper_spec.py

It reads all backend/eval/results/*/summary.csv files and writes real numbers
into the paper spec markdown. Run after all eval conditions have completed.
"""
from __future__ import annotations

import csv
import re
from pathlib import Path
from collections import defaultdict

BACKEND_DIR   = Path(__file__).parent.parent
RESULTS_DIR   = BACKEND_DIR / "eval" / "results"
SPEC_PATH     = Path(__file__).parent.parent.parent / "plan.md"  # update if spec path changes

# The real paper spec lives in the artifact dir — we print a summary to stdout
# and the user can paste the values in manually, or we can write a side-car file.

SUMMARY_OUT = BACKEND_DIR / "eval" / "paper_numbers.md"


def _load_all_summaries() -> dict[str, list[dict]]:
    """Returns {run_id: [row, ...]} for every summary.csv found."""
    summaries: dict[str, list[dict]] = {}
    for csv_path in sorted(RESULTS_DIR.glob("*/summary.csv")):
        run_id = csv_path.parent.name
        with csv_path.open(encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        summaries[run_id] = rows
        print(f"  Loaded {len(rows)} rows from {csv_path.relative_to(BACKEND_DIR)}")
    return summaries


def _macro_f1(rows: list[dict]) -> float | None:
    """Return the macro F1 from the last row (it's the same for all rows of a condition)."""
    for row in rows:
        v = row.get("macro_f1")
        if v and v != "":
            try:
                return round(float(v), 3)
            except ValueError:
                pass
    return None


def _per_field_table(rows: list[dict]) -> str:
    """Build a markdown table of per-field metrics."""
    lines = ["| Field | P | R | F1 | EM | Hall |"]
    lines.append("|---|---|---|---|---|---|")
    for row in rows:
        # each row is one field for one condition
        lines.append(
            f"| {row['field']} "
            f"| {float(row.get('precision', 0)):.3f} "
            f"| {float(row.get('recall', 0)):.3f} "
            f"| {float(row.get('f1', 0)):.3f} "
            f"| {float(row.get('exact_match_accuracy', 0)):.3f} "
            f"| {float(row.get('hallucination_rate', 0)):.3f} |"
        )
    return "\n".join(lines)


def main() -> None:
    print(f"Scanning: {RESULTS_DIR}\n")
    summaries = _load_all_summaries()

    if not summaries:
        print("\nNo summary CSVs found yet. Run eval first:")
        print("  python -m eval.run --conditions llm regex llm_no_grounding --run-id paper_llm_v1")
        return

    output_sections = [
        "# FieldProof — Paper Numbers (auto-generated by fill_paper_spec.py)",
        "",
        "Paste these into paper_spec_filled.md to replace [TO BE FILLED] cells.",
        "",
    ]

    # Group rows by condition within each run
    for run_id, all_rows in sorted(summaries.items()):
        by_condition: dict[str, list[dict]] = defaultdict(list)
        for row in all_rows:
            by_condition[row["condition"]].append(row)

        output_sections.append(f"## Run: `{run_id}`")
        output_sections.append("")

        for cond, rows in sorted(by_condition.items()):
            macro_f1 = _macro_f1(rows)
            hall_rate = None
            for row in rows:
                v = row.get("macro_hallucination_rate")
                if v and v != "":
                    try:
                        hall_rate = round(float(v), 3)
                    except ValueError:
                        pass
                    break

            wer_vals = [float(r.get("mean_wer", 0) or 0) for r in rows if r.get("mean_wer")]
            mean_wer = round(sum(wer_vals) / len(wer_vals), 3) if wer_vals else None

            output_sections.append(f"### Condition: `{cond}`")
            if macro_f1 is not None:
                output_sections.append(f"- **Macro F1:** {macro_f1}")
            if hall_rate is not None:
                output_sections.append(f"- **Macro hallucination rate:** {hall_rate}")
            if mean_wer is not None:
                output_sections.append(f"- **Mean WER:** {mean_wer}")
            output_sections.append("")
            output_sections.append(_per_field_table(rows))
            output_sections.append("")

    SUMMARY_OUT.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_OUT.write_text("\n".join(output_sections), encoding="utf-8")
    print(f"\n[OK] Paper numbers written to: {SUMMARY_OUT}")
    print("\nNow open paper_numbers.md and paste the values into paper_spec_filled.md.")
    print("Replace the corresponding [TO BE FILLED] cells with the numbers above.")


if __name__ == "__main__":
    main()
